<#
.SYNOPSIS
    Regenerates Modules\TalentNames.lua from Blizzard's own client data.

.DESCRIPTION
    The talent loadout table labels its columns with the naming convention's
    prefix -- the initials of a spec and a hero talent, "SA" for Shadow Archon.
    Those initials have to be the ENGLISH ones, because that is what the
    loadout names themselves use, and they are the same names whatever client
    the player runs. Asking the game gives localised names: on a zhCN client
    C_Traits.GetSubTreeInfo returns 执政官 for Archon, whose initial matches
    nothing anybody has ever typed.

    So the English names are baked in, keyed by the numeric IDs the API hands
    back. Both IDs are stable client data, and the two tables below are small
    enough to read and check by eye.

    Source is wago.tools, which serves Blizzard's DB2 tables as CSV with a
    locale parameter:

      ChrSpecialization  ID -> Name_lang   (player specs: ClassID 1-13,
                                            PetTalentType 0, not "Initial")
      TraitSubTree       ID -> Name_lang   (hero talents; test rows say DNT)

    Run after a patch that adds a spec or a hero talent. Nothing breaks
    without it -- an unknown ID falls back to the localised name, so a new
    hero talent shows up with a localised initial until this is re-run.

.EXAMPLE
    .\Tools\update-talentnames.ps1
#>

[CmdletBinding()]
param()

$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
$out = Join-Path $root "Modules\TalentNames.lua"
$tmp = Join-Path ([IO.Path]::GetTempPath()) "animods-talentnames"
New-Item -ItemType Directory -Force $tmp | Out-Null

function Get-Db2($table) {
    $path = Join-Path $tmp "$table.csv"
    Write-Host "  fetching $table ..." -NoNewline
    Invoke-WebRequest -Uri "https://wago.tools/db2/$table/csv?locale=enUS" `
        -OutFile $path -UseBasicParsing -TimeoutSec 180
    $rows = Import-Csv $path
    Write-Host " $($rows.Count) rows"
    return $rows
}

Write-Host "Reading Blizzard client data (enUS)" -ForegroundColor Cyan

$specs = Get-Db2 "ChrSpecialization" |
    Where-Object {
        $_.Name_lang -and $_.Name_lang -ne "Initial" -and
        [int]$_.PetTalentType -eq 0 -and
        [int]$_.ClassID -ge 1 -and [int]$_.ClassID -le 13
    } |
    Sort-Object { [int]$_.ClassID }, { [int]$_.OrderIndex }

$heroes = Get-Db2 "TraitSubTree" |
    Where-Object { $_.Name_lang -and $_.Name_lang -notmatch "DNT" -and
                   $_.Name_lang -notmatch "^UI Test" } |
    Sort-Object { [int]$_.ID }

if ($specs.Count -lt 30 -or $heroes.Count -lt 20) {
    throw "Suspiciously few rows ($($specs.Count) specs, $($heroes.Count) hero talents) -- refusing to write."
}

$sb = [Text.StringBuilder]::new()
function Emit($line) { [void]$sb.AppendLine($line) }

Emit "-- TalentNames -- English spec and hero talent names, by ID."
Emit "--"
Emit "-- GENERATED by Tools\update-talentnames.ps1 from Blizzard's own DB2"
Emit "-- tables (ChrSpecialization, TraitSubTree) at the enUS locale. Do not"
Emit "-- edit by hand; re-run the script after a patch adds a spec or a hero"
Emit "-- talent."
Emit "--"
Emit "-- Why English rather than what the client reports: the loadout naming"
Emit "-- convention spells a prefix as the two English initials -- SA is Shadow"
Emit "-- Archon -- and those names are what a player types whatever locale they"
Emit "-- play in. C_Traits.GetSubTreeInfo answers in the client's language, so"
Emit "-- on a zhCN client it returns 'Archon' as a character whose initial"
Emit "-- matches no loadout name at all."
Emit ""
Emit "local AniMods = _G.AniMods"
Emit ""
Emit "AniMods.TalentNames = {"
Emit "    -- specID -> English specialization name"
Emit "    spec = {"

$lastClass = $null
foreach ($s in $specs) {
    if ($lastClass -ne $s.ClassID) {
        if ($null -ne $lastClass) { Emit "" }
        $lastClass = $s.ClassID
    }
    Emit ("        [{0}] = {1}," -f $s.ID, ('"' + $s.Name_lang + '"'))
}

Emit "    },"
Emit ""
Emit "    -- subTreeID -> English hero talent name"
Emit "    hero = {"
foreach ($h in $heroes) {
    Emit ("        [{0}] = {1}," -f $h.ID, ('"' + $h.Name_lang + '"'))
}
Emit "    },"
Emit "}"

# No BOM: the rest of the addon's Lua has none, and luac rejects one.
[IO.File]::WriteAllText($out, $sb.ToString(), [Text.UTF8Encoding]::new($false))

Write-Host "`nWrote $out" -ForegroundColor Green
Write-Host "  $($specs.Count) specs, $($heroes.Count) hero talents"
Write-Host "`nRemember: Modules\TalentNames.lua must be listed in AniMods.toc."
